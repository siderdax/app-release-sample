import path from 'node:path';
import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

function buildContentDisposition(fileName: string): string {
  const asciiFallback = fileName
    .replace(/[^\x20-\x7E]/g, '_')
    .replace(/["\\]/g, '_');
  const utf8Encoded = encodeURIComponent(fileName).replace(
    /['()*]/g,
    (ch) => `%${ch.charCodeAt(0).toString(16).toUpperCase()}`,
  );
  return `attachment; filename="${asciiFallback}"; filename*=UTF-8''${utf8Encoded}`;
}

/**
 * 샘플 웹앱용 다운로드 준비 엔드포인트 (POST)
 */
export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const rawPath = typeof body?.path === 'string' ? body.path.trim() : '';

    if (!rawPath) {
      return NextResponse.json(
        { ok: false, error: { code: 'INVALID_PATH', message: '파일 경로가 전달되지 않았습니다.' } },
        { status: 400 },
      );
    }

    // 모의 다운로드 준비 딜레이 (150ms 체감)
    await new Promise((r) => setTimeout(r, 150));

    const fileName = path.basename(rawPath);
    return NextResponse.json({
      ok: true,
      ready: true,
      fileName,
      downloadUrl: `/api/download?path=${encodeURIComponent(rawPath)}`,
    });
  } catch {
    return NextResponse.json(
      { ok: false, error: { code: 'BAD_REQUEST', message: '잘못된 요청 형식입니다.' } },
      { status: 400 },
    );
  }
}

/**
 * 샘플 웹앱용 모의 파일 다운로드 스트리밍 엔드포인트 (GET)
 */
export async function GET(request: NextRequest) {
  const rawPath = (request.nextUrl.searchParams.get('path') ?? '').trim();

  if (!rawPath) {
    return NextResponse.json(
      { ok: false, error: { code: 'INVALID_PATH', message: '다운로드할 파일 경로가 지정되지 않았습니다.' } },
      { status: 400 },
    );
  }

  const fileName = path.basename(rawPath);
  const samplePayload = `================================================================================
INDUSTRIAL SOFTWARE RELEASE SAMPLE WEB APP
================================================================================
File Name    : ${fileName}
Relative Path: ${rawPath}
Status       : Sample Mock Download Successful
Description  : This is a verified mock distribution asset generated by the
               App Release Sample web application.
Created At   : ${new Date().toISOString()}
================================================================================
`;

  const headers = new Headers();
  headers.set('Content-Type', 'application/octet-stream');
  headers.set('Content-Disposition', buildContentDisposition(fileName));
  headers.set('Content-Length', String(Buffer.byteLength(samplePayload, 'utf-8')));

  return new NextResponse(samplePayload, {
    status: 200,
    headers,
  });
}
